#!/usr/bin/env bash
# Build distributables from skills/readme-review:
#   prompts/readme-review-prompt.md  single-file prompt for chat tools without skill support
#   dist/readme-review.zip           skill bundle for claude.ai / Claude Code upload
#   feedback/questions.md            from feedback/survey-spec.json (also done by survey-questions.yml)
# Usage: scripts/build.sh            (run from repo root)
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
skill="$root/skills/readme-review"
version="$(tr -d '[:space:]' < "$skill/VERSION")"
feedback="$(tr -d '[:space:]' < "$skill/FEEDBACK_URL" 2>/dev/null || true)"
feedback="${feedback//\{VERSION\}/$version}"
out="$root/prompts/readme-review-prompt.md"

mkdir -p "$root/prompts" "$root/dist"

{
  echo "<!-- GENERATED by scripts/build.sh from skills/readme-review (v$version). Do not edit by hand. -->"
  echo
  echo "# README review prompt (v$version)"
  echo
  echo "Paste everything below into a chat tool, then attach or paste the README (and, if available, the replication package or its file listing)."
  echo
  echo "Where the text refers to files in \`references/\`, use the matching appendix below."
  echo "Skill version: $version."
  if [ -n "$feedback" ]; then
    echo "Feedback link (\`FEEDBACK_URL\`, version already filled in): $feedback"
  else
    echo "Feedback link: none; omit the feedback line."
  fi
  echo
  echo "---"
  echo
  # SKILL.md body without YAML front matter
  awk 'BEGIN{n=0} /^---$/ && n<2 {n++; next} n>=2' "$skill/SKILL.md"
  for f in template-sections style-guide package-checks report-format; do
    echo
    echo "---"
    echo
    echo "## Appendix: references/$f.md"
    echo
    # demote headings by one level so they nest under the appendix heading
    awk '/^```/{fence=!fence} !fence && /^#+ /{$0="#"$0} {print}' "$skill/references/$f.md"
  done
} > "$out"

python3 "$root/scripts/create_survey.py" --markdown >/dev/null

rm -f "$root/dist/readme-review.zip"
(cd "$root/skills" && zip -qr "$root/dist/readme-review.zip" readme-review)

echo "Built $out and dist/readme-review.zip (v$version)"
